// Builds supabase/seed.sql from client/src/data/products.js (the single source of truth for the sample
// catalogue). Run after editing products:   npm run seed:generate
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { PRODUCTS } = await import(pathToFileURL(path.join(root, 'client/src/data/products.js')).href);

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const rows = PRODUCTS.map(
  (p, i) =>
    `  (${q(p.id)}, ${q(p.name)}, ${q(p.cat)}, ${q(p.art)}, ${q(p.image)}, ${p.price}, ${p.mrp}, ${p.rating}, ${p.reviews}, ${q(p.badge)}, ${i})`
);

const sql = `-- GENERATED by scripts/generate-seed.mjs from client/src/data/products.js. Do not edit by hand.
-- Re-running is safe: rows are upserted by id.
insert into public.products (id, name, cat, art, image, price, mrp, rating, reviews, badge, sort_order) values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, cat = excluded.cat, art = excluded.art, image = excluded.image,
  price = excluded.price, mrp = excluded.mrp, rating = excluded.rating, reviews = excluded.reviews,
  badge = excluded.badge, sort_order = excluded.sort_order;
`;

fs.writeFileSync(path.join(root, 'supabase/seed.sql'), sql);
console.log(`supabase/seed.sql written (${PRODUCTS.length} products)`);
